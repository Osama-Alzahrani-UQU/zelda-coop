"""Generates the winmm.dll proxy's export stubs from the system's winmm.dll.

The proxy (src/proxy/winmm_proxy.c) is a winmm.dll placed beside bin\\longshot.exe: Windows loads it first (winmm is not a
KnownDLL), it forwards every winmm export to the real System32\\winmm.dll and loads the co-op mod.

Writes src/proxy/winmm_exports.def and src/proxy/winmm_stubs.S (one `jmp *slot(%rip)` per export) and
src/proxy/winmm_names.h (the names, in slot order).
Run: python -I tools/gen_winmm_proxy.py
"""
import os
import sys

import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "proxy")


def main():
    sysdir = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32")
    pe = pefile.PE(os.path.join(sysdir, "winmm.dll"), fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    names = []
    ordinals = {}
    for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        if e.name:
            n = e.name.decode()
            names.append(n)
            ordinals[n] = e.ordinal
    names = sorted(set(names), key=lambda n: ordinals[n])
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "winmm_exports.def"), "w", newline="\n") as f:
        f.write("LIBRARY winmm\nEXPORTS\n")
        for i, n in enumerate(names):
            f.write("    %s=lsc_stub_%d @%d\n" % (n, i, ordinals[n]))
    with open(os.path.join(OUT, "winmm_stubs.S"), "w", newline="\n") as f:
        f.write("/* Generated by tools/gen_winmm_proxy.py: one jump through lsc_real[i] per winmm export. */\n")
        f.write("    .text\n")
        for i, n in enumerate(names):
            f.write("    .globl lsc_stub_%d\n    .p2align 4\nlsc_stub_%d:\n    jmpq *lsc_real+%d(%%rip)\n" % (i, i, i * 8))
    with open(os.path.join(OUT, "winmm_names.h"), "w", newline="\n") as f:
        f.write("/* Generated by tools/gen_winmm_proxy.py: winmm's exports in slot order. */\n")
        f.write("#define LSC_WINMM_COUNT %d\n" % len(names))
        f.write("static const char *const lsc_winmm_names[LSC_WINMM_COUNT] = {\n")
        for n in names:
            f.write('    "%s",\n' % n)
        f.write("};\n")
    print("winmm exports:", len(names))


if __name__ == "__main__":
    sys.exit(main())
